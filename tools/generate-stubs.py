#!/usr/bin/env python3
"""
Declare the UnrealScript classes a CrimeCraft map needs, so the engine can
deserialise what the map stored.

WHY STUBS
---------
The maps import classes from `CrimeCraft.u` that our engine does not have. Loading the
game's own package is not an option: it was **cooked at engine build 4701** and our SDK
is **10897**, so it desynchronises. The route taken here is **stubs**: declare the
classes so the engine can read the data, without reproducing behaviour.

The vehicle is `EditPackages`, which the engine turns into `DemoGame/Script/<Pkg>.u`.
**The folder is what decides, not the ini line** -- which is why `EditPackages=DemoGame`
is off: its source folder does not exist.

WHAT IT DOES
------------
Takes the `.uc` files exported from the game and adapts them: strips `native` from the
class declaration; marks the extraction artefacts that are not valid UnrealScript; and
**withdraws** stubs for classes the list no longer asks for -- the compiler reads the
*folder*, so an obsolete stub compiles anyway and drags in its own unresolved types.

WHAT IT DOES NOT DO
-------------------
**It does not check that every referenced type resolves.** Its own docstring used to
claim it did, and it did not. The script compiler does that properly, in ten seconds,
naming the exact type and line; reimplementing it approximately would only add false
positives needing their own debugging.

**And it decides nothing about what it does not understand -- it reports it.** A
generator that silently repairs the artefacts it cannot parse produces stubs that
compile and do not do what they appear to.

THE RECORD
----------
This file carried 3,284 lines of measured detail -- counts, traps, and the reasoning
behind each rule -- written as comments. **All of it is preserved, and this file is the
code without it:**

    generate-stubs-commented.py     the same file with every comment intact (Spanish)
    generate-stubs-comments.md      the same content as English documentation

Read those before changing a rule here. Most of the constants below are not
preferences: they are measurements, and the measurement is in the document.

USAGE
-----
    python -I generate-stubs.py --dry-run --origen <exported .uc dir>
                                --sdk <Development/Src> --datos <catalogues dir>
"""


